// Package items is an experimental item composer under examples, not an extracted
// production API. New(Config) binds authored grants/pools to an instance; real
// effects outputs control attachment and recovery on a caller-owned bus.
//
// Offers exposes copied grant data and source identity. Use returns a consumer's
// typed resolution outcome while owning only this item's charge accounting.
// The consumer validates/interprets the ability and delivers the outcome once;
// this package imports no rulebook, rolls no dice and mutates no character HP.
//
// Data saves only identity and pool counts. The generated effects recipe has one
// state and no mutable bag; arbitrary passive/stateful item recipes are not part
// of this first cut. Attachment/rest eligibility is supplied explicitly by the
// caller and is not an equipment or attunement rule. See README.md and PLAN.md.
package items
